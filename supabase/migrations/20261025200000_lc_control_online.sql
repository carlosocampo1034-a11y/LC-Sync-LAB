create policy customers_read on public.customers for select to authenticated
  using (user_id = (select auth.uid()) or (select public.lc_is_staff()));

-- Un cliente que se registra en la app queda en el directorio (o se enlaza a la ficha creada por despacho)
create or replace function lc_private.link_customer() returns trigger
  language plpgsql security definer set search_path = ''
  as $$
  declare v_email text; v_id bigint;
  begin
    if new.role <> 'CUSTOMER' then return new; end if;
    if exists (select 1 from public.customers where user_id = new.id) then return new; end if;
    select email into v_email from auth.users where id = new.id;
    select id into v_id from public.customers
     where user_id is null and v_email is not null and lower(email) = lower(v_email) order by id limit 1;
    if v_id is not null then
      update public.customers set user_id = new.id, updated_at = public.lc_now_ms() where id = v_id;
    else
      insert into public.customers (user_id, nombre, email)
      values (new.id, left(coalesce(nullif(new.display_name, ''), split_part(coalesce(v_email, 'cliente'), '@', 1), 'cliente'), 80),
              v_email);
    end if;
    return new;
  end; $$;
revoke all on function lc_private.link_customer() from public, anon, authenticated;
drop trigger if exists lc_profile_link_customer on public.profiles;
create trigger lc_profile_link_customer after insert or update of role on public.profiles
  for each row execute function lc_private.link_customer();
