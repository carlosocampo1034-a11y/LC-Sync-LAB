-- ¿El usuario autenticado es despacho activo? (security definer: evita recursión de RLS en profiles)
create or replace function public.lc_is_staff() returns boolean
  language sql stable security definer set search_path = ''
  as $$ select exists (select 1 from public.profiles
                        where id = (select auth.uid()) and role in ('ADMIN','DISPATCHER') and active) $$;
revoke all on function public.lc_is_staff() from public, anon;
grant execute on function public.lc_is_staff() to authenticated, service_role;

drop policy if exists profiles_read_staff on public.profiles;
create policy profiles_read_staff on public.profiles for select to authenticated using ((select public.lc_is_staff()));

