create or replace function lc_private.job_notify() returns trigger
  language plpgsql security definer set search_path = ''
  as $$ begin
    if tg_op = 'INSERT' then
      if new.origin = 'CUSTOMER' then
        insert into public.notifications (user_id, job_id, tipo, titulo, cuerpo)
        values (null, new.id, 'NUEVA_SOLICITUD', 'Nueva solicitud #' || new.id, left(new.descripcion, 200));
      end if;
      return new;
    end if;
    if new.technician_id is not null and new.technician_id is distinct from old.technician_id then
      insert into public.notifications (user_id, job_id, tipo, titulo, cuerpo)
      values (new.technician_id, new.id, 'ASIGNACION', 'Nueva orden asignada #' || new.id,
              left(coalesce(new.direccion, '') || ' · ' || new.descripcion, 200));
    end if;
    if new.estado is distinct from old.estado then
      if new.customer_id is not null then
        insert into public.notifications (user_id, job_id, tipo, titulo, cuerpo)
        values (new.customer_id, new.id, 'ESTADO', 'Tu solicitud #' || new.id || ': ' || new.estado, null);
      end if;
      insert into public.notifications (user_id, job_id, tipo, titulo, cuerpo)
      values (null, new.id, 'ESTADO', 'Orden #' || new.id || ' → ' || new.estado, new.technician_code);
    end if;
    return new;
  end; $$;
revoke all on function lc_private.job_notify() from public, anon, authenticated;
drop trigger if exists lc_jobs_notify on public.jobs;
create trigger lc_jobs_notify after insert or update of estado, technician_id on public.jobs
