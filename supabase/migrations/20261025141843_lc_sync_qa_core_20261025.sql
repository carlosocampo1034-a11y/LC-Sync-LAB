
create schema if not exists lc_private;
revoke all on schema lc_private from public, anon, authenticated;

create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 role text not null default 'CUSTOMER' check (role in ('ADMIN','DISPATCHER','TECHNICIAN','CUSTOMER')),
 display_name text,
 technician_code text unique,
 created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to authenticated;
create policy profiles_read_own on public.profiles for select to authenticated
 using (id = (select auth.uid()));

create function lc_private.bootstrap_profile() returns trigger
 language plpgsql security definer set search_path = ''
 as $$ begin
   insert into public.profiles (id,role,display_name)
   values (new.id,'CUSTOMER',null)
   on conflict (id) do nothing;
   return new;
 end; $$;
revoke all on function lc_private.bootstrap_profile() from public, anon, authenticated;
create trigger lc_auth_profile_after_signup after insert on auth.users
 for each row execute function lc_private.bootstrap_profile();

create table public.jobs (
 id bigint generated by default as identity primary key,
 version integer not null default 1 check (version > 0),
 estado text not null default 'PENDIENTE',
 estado_dispatch text,
 prioridad text,
 categoria text,
 origin text not null default 'CUSTOMER',
 created_by uuid not null references auth.users(id),
 customer_id uuid references auth.users(id),
 technician_id uuid references auth.users(id),
 technician_code text,
 cliente text not null,
 telefono text,
 direccion text,
 descripcion text not null,
 notas text,
 horas numeric(10,2),
 programado_para bigint,
 client_updated_at bigint,
 created_at bigint not null default (floor(extract(epoch from clock_timestamp()) * 1000)::bigint),
 updated_at bigint not null default (floor(extract(epoch from clock_timestamp()) * 1000)::bigint)
);
create index jobs_owner_idx on public.jobs(customer_id, updated_at);
create index jobs_technician_idx on public.jobs(technician_id, updated_at);
create index jobs_updated_idx on public.jobs(updated_at);
alter table public.jobs enable row level security;
revoke all on public.jobs from anon, authenticated;
grant select on public.jobs to authenticated;
create policy jobs_read_authorized on public.jobs for select to authenticated
 using (
  customer_id = (select auth.uid()) or
  technician_id = (select auth.uid()) or
  exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role in ('ADMIN','DISPATCHER'))
 );

create table public.job_history (
 id bigint generated always as identity primary key,
 job_id bigint not null references public.jobs(id) on delete cascade,
 version integer not null,
 field text not null,
 actor uuid references auth.users(id),
 old_value text,
 new_value text,
 created_at timestamptz not null default now(),
 unique(job_id,version,field)
);
create index job_history_job_version_idx on public.job_history(job_id,version);
alter table public.job_history enable row level security;
revoke all on public.job_history from anon,authenticated;
grant select on public.job_history to authenticated;
create policy history_read_authorized on public.job_history for select to authenticated
 using (exists (
   select 1 from public.jobs j where j.id=job_id
 ));

create table public.job_conflicts (
 id bigint generated always as identity primary key,
 job_id bigint not null references public.jobs(id) on delete cascade,
 field text not null,
 base_version integer not null,
 server_version integer not null,
 server_value text,
 client_value text,
 actor uuid references auth.users(id),
 estado text not null default 'PENDIENTE',
 created_at timestamptz not null default now()
);
create index job_conflicts_job_idx on public.job_conflicts(job_id);
alter table public.job_conflicts enable row level security;
revoke all on public.job_conflicts from anon,authenticated;
grant select on public.job_conflicts to authenticated;
create policy conflicts_read_dispatch on public.job_conflicts for select to authenticated
 using (exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.role in ('ADMIN','DISPATCHER')));

create table public.sync_receipts (
 user_id uuid not null references auth.users(id),
 device_id text not null check(length(device_id) between 1 and 128),
 job_id bigint not null references public.jobs(id),
 client_updated_at bigint not null,
 status text not null check (status in ('ACCEPTED','CONFLICT','REJECTED')),
 version integer,
 ts timestamptz not null default now(),
 primary key(user_id,device_id,job_id,client_updated_at)
);
alter table public.sync_receipts enable row level security;
revoke all on public.sync_receipts from anon,authenticated;
grant select on public.sync_receipts to authenticated;
create policy receipts_read_own on public.sync_receipts for select to authenticated
 using(user_id = (select auth.uid()));

-- Row-level visibility of changed jobs, with reconnect reconciliation by updated_at.
alter table public.jobs replica identity full;
alter publication supabase_realtime add table public.jobs;
;
